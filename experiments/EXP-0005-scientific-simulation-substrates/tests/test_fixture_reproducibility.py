"""
EXP-0005 WP-00: Deterministic Fixture & SHA-256 Reproducibility Unit Tests.

Verifies:
  1. Fixture byte identity and SHA-256 hashes match `fixtures/manifest_sha256.json`.
  2. Regenerating fixtures into a fresh temporary directory yields bit-identical bytes.
  3. Directed edges have no self-loops, no duplicate (src_id, dst_id) pairs, strictly positive
     delays (`delay_ms > 0`), and deterministic `(src_id, dst_id, delay_ms, weight_mV)` sort order.
  4. External events are sorted by `(t_ms, target_id, src_id, ordinal)` with `t_ms >= 0`.
  5. Multi-module stratified stimulus (`pilot_disconnected_n128_d4_s11` and `pilot_modular_n128_d4_s11`)
     delivers exactly 16 external events to each of the 4 contiguous 32-node modules, while
     the localized control (`pilot_disconnected_localized_n128_d4_s11`) restricts all 64 external
     events to Module 0 (`[0, 32)`).
  6. Total checked-in fixture footprint is strictly <= 1 MiB.
  7. Historical EXP-0004 config SHA-256 provenance is recorded accurately without mutating EXP-0004.
"""

from __future__ import annotations

import csv
import hashlib
import json
import tempfile
import unittest
from pathlib import Path

from helper_imports import (
    EXP0005_ROOT,
    load_fixture_generator_module,
)


class TestFixtureReproducibility(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.gen = load_fixture_generator_module()
        cls.fixtures_dir = EXP0005_ROOT / "fixtures"
        cls.manifest_path = cls.fixtures_dir / "manifest_sha256.json"

    def test_manifest_exists_and_size_under_1mib(self) -> None:
        self.assertTrue(self.manifest_path.exists(), "fixtures/manifest_sha256.json must exist")
        manifest = json.loads(self.manifest_path.read_text(encoding="utf-8"))
        self.assertEqual(manifest["schema_version"], "sc05-fixture-manifest-v1")

        total_bytes = 0
        for fname, meta in manifest["files"].items():
            fpath = self.fixtures_dir / fname
            self.assertTrue(fpath.exists(), f"Missing fixture file {fname}")
            raw = fpath.read_bytes()
            actual_sha = hashlib.sha256(raw).hexdigest()
            self.assertEqual(actual_sha, meta["sha256"], f"SHA-256 mismatch for {fname}")
            self.assertEqual(len(raw), meta["byte_count"], f"Byte count mismatch for {fname}")
            total_bytes += len(raw)

        self.assertLessEqual(total_bytes, 1024 * 1024, "Committed fixtures must stay <= 1 MiB")

    def test_regeneration_byte_identity(self) -> None:
        with tempfile.TemporaryDirectory() as tmpdir:
            tmp_path = Path(tmpdir)
            regen_manifest = self.gen.build_default_wp00_fixtures(tmp_path)
            committed_manifest = json.loads(self.manifest_path.read_text(encoding="utf-8"))
            self.assertEqual(regen_manifest, committed_manifest)

            for fname in committed_manifest["files"]:
                self.assertEqual(
                    (self.fixtures_dir / fname).read_bytes(),
                    (tmp_path / fname).read_bytes(),
                    f"Regenerated bytes differed for {fname}",
                )

    def test_edges_direction_positive_delay_no_duplicates_and_sorted(self) -> None:
        edge_files = [
            "golden_c_causal_chain_edges.csv",
            "pilot_disconnected_n128_d4_s11_edges.csv",
            "pilot_modular_n128_d4_s11_edges.csv",
        ]
        for fname in edge_files:
            fpath = self.fixtures_dir / fname
            with fpath.open("r", encoding="utf-8", newline="") as f:
                reader = csv.DictReader(f)
                self.assertEqual(reader.fieldnames, ["src_id", "dst_id", "delay_ms", "weight_mV"])
                seen_pairs = set()
                prev_key = None
                row_count = 0
                for row in reader:
                    row_count += 1
                    src = int(row["src_id"])
                    dst = int(row["dst_id"])
                    delay = float(row["delay_ms"])
                    weight = float(row["weight_mV"])

                    self.assertNotEqual(src, dst, f"Self-edge detected in {fname}: {src}->{dst}")
                    self.assertGreater(delay, 0.0, f"Non-positive delay in {fname}: {delay}")
                    self.assertNotIn((src, dst), seen_pairs, f"Duplicate edge ({src}, {dst}) in {fname}")
                    seen_pairs.add((src, dst))

                    key = (src, dst, round(delay, 8), round(weight, 8))
                    if prev_key is not None:
                        self.assertGreater(key, prev_key, f"Unsorted edge row in {fname}")
                    prev_key = key

                self.assertGreater(row_count, 0)

    def test_events_sorted_tie_order_and_non_negative_time(self) -> None:
        event_files = [
            "golden_c_causal_chain_events.csv",
            "golden_c_tie_adversarial_events.csv",
            "pilot_disconnected_n128_d4_s11_events.csv",
            "pilot_disconnected_localized_n128_d4_s11_events.csv",
            "pilot_modular_n128_d4_s11_events.csv",
        ]
        for fname in event_files:
            fpath = self.fixtures_dir / fname
            with fpath.open("r", encoding="utf-8", newline="") as f:
                reader = csv.DictReader(f)
                self.assertEqual(
                    reader.fieldnames,
                    ["t_ms", "target_id", "src_id", "ordinal", "weight_mV"],
                )
                prev_key = None
                for row in reader:
                    t_ms = float(row["t_ms"])
                    target_id = int(row["target_id"])
                    src_id = int(row["src_id"])
                    ordinal = int(row["ordinal"])
                    self.assertGreaterEqual(t_ms, 0.0, f"Negative timestamp in {fname}")
                    key = (round(t_ms, 8), target_id, src_id, ordinal)
                    if prev_key is not None:
                        self.assertGreater(key, prev_key, f"Events not strictly sorted by tie key in {fname}")
                    prev_key = key

    def test_stratified_vs_localized_module_stimulus_distribution(self) -> None:
        # Stratified pilot fixtures must stimulate all 4 modules equally (16 external events per 32-node module)
        for fname in ("pilot_disconnected_n128_d4_s11_events.csv", "pilot_modular_n128_d4_s11_events.csv"):
            mod_counts = {0: 0, 1: 0, 2: 0, 3: 0}
            with (self.fixtures_dir / fname).open("r", encoding="utf-8", newline="") as f:
                for row in csv.DictReader(f):
                    tgt = int(row["target_id"])
                    mod_counts[tgt // 32] += 1
            self.assertEqual(
                mod_counts,
                {0: 16, 1: 16, 2: 16, 3: 16},
                f"Expected equal 16-event stratification across 4 modules in {fname}, got {mod_counts}",
            )

        # Localized control must stimulate only Module 0 (all 64 external events in [0, 8) at f=0.25)
        loc_counts = {0: 0, 1: 0, 2: 0, 3: 0}
        with (self.fixtures_dir / "pilot_disconnected_localized_n128_d4_s11_events.csv").open(
            "r", encoding="utf-8", newline=""
        ) as f:
            for row in csv.DictReader(f):
                tgt = int(row["target_id"])
                self.assertLess(tgt, 8, f"Expected localized target in [0, 8) at f=0.25, got {tgt}")
                loc_counts[tgt // 32] += 1
        self.assertEqual(loc_counts, {0: 64, 1: 0, 2: 0, 3: 0})

    def test_localized_first_module_strictly_bounded_to_module0_at_high_active_fraction(self) -> None:
        """
        Regression test for Review #2 P1-B: at active_fraction=0.50 and 1.00 with N=128,
        num_modules=4 (module 0 = [0, 32)), localized_first_module MUST strictly constrain
        target_id to [0, 32) and NEVER spill into Modules 1..3.
        """
        b025 = self.gen.compute_stimulus_target_budget(128, 4, 0.25, "localized_first_module")
        self.assertEqual(b025["target_pool_per_module"], [8, 0, 0, 0])
        self.assertEqual(b025["total_target_pool_neurons"], 8)

        b050 = self.gen.compute_stimulus_target_budget(128, 4, 0.50, "localized_first_module")
        self.assertEqual(b050["target_pool_per_module"], [16, 0, 0, 0])
        self.assertEqual(b050["total_target_pool_neurons"], 16)

        b100 = self.gen.compute_stimulus_target_budget(128, 4, 1.00, "localized_first_module")
        self.assertEqual(b100["target_pool_per_module"], [32, 0, 0, 0])
        self.assertEqual(b100["total_target_pool_neurons"], 32)

        for frac, max_target_exclusive in ((0.25, 8), (0.50, 16), (1.00, 32)):
            events = self.gen.generate_external_events(
                num_nodes=128,
                num_events=128,
                horizon_ms=100.0,
                seed=11,
                active_fraction=frac,
                num_modules=4,
                stimulus_distribution="localized_first_module",
            )
            self.assertEqual(len(events), 128)
            for ev in events:
                tgt = int(ev[1])
                self.assertGreaterEqual(tgt, 0)
                self.assertLess(
                    tgt,
                    max_target_exclusive,
                    f"Localized stimulus at active_fraction={frac} spilled to target_id={tgt} >= {max_target_exclusive}",
                )
                self.assertEqual(tgt // 32, 0, f"Event leaked outside Module 0 into Module {tgt // 32}")

    def test_topology_parameter_validation_fails_fast_on_impossible_degree(self) -> None:
        """
        Regression test for Review #2 P2-1: generate_Topology_edges must raise ValueError
        immediately when out_degree >= module_size on disconnected graphs or when out_degree >= num_nodes.
        """
        with self.assertRaises(ValueError):
            # N=8, 4 modules -> module_size=2, out_degree=4 is impossible without self/cross edges
            self.gen.generate_Topology_edges(
                topology="disconnected",
                num_nodes=8,
                out_degree=4,
                seed=11,
                num_modules=4,
            )
        with self.assertRaises(ValueError):
            self.gen.generate_Topology_edges(
                topology="random",
                num_nodes=8,
                out_degree=8,
                seed=11,
                num_modules=2,
            )
        with self.assertRaises(ValueError):
            self.gen.generate_Topology_edges(
                topology="modular_sbm",
                num_nodes=16,
                out_degree=4,
                seed=11,
                num_modules=0,
            )

    def test_exp0004_read_only_provenance_hashes(self) -> None:
        manifest = json.loads(self.manifest_path.read_text(encoding="utf-8"))
        prov = manifest["historical_exp0004_provenance"]
        self.assertTrue(prov["read_only_verified"])
        self.assertFalse(prov["cross_language_hash_equality_claimed"])
        self.assertEqual(
            prov["files"]["canonical_modular_sbm_n100k.json"]["sha256"],
            "673d9f5cf1c6523d5fb60a301c631380ae87fd17c1d895a252f66ee94ebf9b3c",
        )
        self.assertEqual(
            prov["files"]["canonical_disconnected_control_n100k.json"]["sha256"],
            "5cfc89cf8665c0493b9f0235b7159ec78e3c83019fe3128823f300e346df8a16",
        )
        self.assertEqual(
            prov["files"]["benchmark_schema_v1.json"]["sha256"],
            "902952859c911a20d7c455a30be60a9bd96c9476222021541f165cec657bf968",
        )

    def test_report_md_byte_counts_and_hashes_match_manifest(self) -> None:
        manifest = json.loads(self.manifest_path.read_text(encoding="utf-8"))
        report_text = (EXP0005_ROOT / "REPORT.md").read_text(encoding="utf-8")

        for fname, meta in manifest["files"].items():
            expected_bytes_str = f"{meta['byte_count']:,}"
            expected_sha = meta["sha256"]
            self.assertIn(fname, report_text, f"REPORT.md missing fixture filename {fname}")
            self.assertIn(expected_sha, report_text, f"REPORT.md missing exact SHA-256 for {fname}")
            self.assertIn(
                f"| [`fixtures/{fname}`](fixtures/{fname}) | {expected_bytes_str} | `{expected_sha}` |",
                report_text,
                f"REPORT.md byte count or SHA-256 table row mismatch for {fname}",
            )

        for wkey, wmeta in manifest["workloads"].items():
            self.assertIn(
                wmeta["workload_instance_id"],
                report_text,
                f"REPORT.md missing workload_instance_id for {wkey}",
            )


if __name__ == "__main__":
    unittest.main()
